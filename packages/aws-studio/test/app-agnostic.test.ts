import assert from "node:assert/strict";
import { readdirSync, readFileSync } from "node:fs";
import path from "node:path";
import test from "node:test";
import { generatedOutputs } from "../scripts/generated-paths";

/**
 * The framework package is the same for every application: what `framework:generate` derives
 * from one application's declarations (target ids, agent tool schemas, the replay manifest,
 * the endpoint list for its CDK version) is generated into that application, in the
 * @repo/framework-generated workspace the framework reads it from.
 */

const framework = path.resolve(__dirname, "..");

function sources(directory: string): string[] {
  return readdirSync(directory, { withFileTypes: true }).flatMap(entry => entry.isDirectory() ? sources(path.join(directory, entry.name)) : entry.name.endsWith(".ts") ? [path.join(directory, entry.name)] : []);
}

test("the framework package holds no projection generated from an application", () => {
  const generated = sources(path.join(framework, "src")).filter(file => /generated by npm run framework:generate/i.test(readFileSync(file, "utf8").slice(0, 400)));
  assert.deepEqual(generated.map(file => path.relative(framework, file)), []);
});

test("framework source reads application projections only through @repo/framework-generated", () => {
  const relative = sources(path.join(framework, "src")).filter(file => /from\s+["'](?:\.\.?\/)+generated\//.test(readFileSync(file, "utf8")));
  assert.deepEqual(relative.map(file => path.relative(framework, file)), []);
});

test("every framework:generate output lies in the application, outside the framework package", () => {
  const application = path.resolve("/application");
  for (const [name, file] of Object.entries(generatedOutputs(application))) {
    assert.ok(file.startsWith(application + path.sep), `${name} is written inside the application`);
    assert.ok(!file.startsWith(path.join(application, "packages/aws-studio") + path.sep), `${name} is not written into the framework package: ${file}`);
  }
});

test("the framework names the application's generated package as a peer it does not ship", () => {
  const manifest = JSON.parse(readFileSync(path.join(framework, "package.json"), "utf8")) as { peerDependencies?: Record<string, string>; dependencies?: Record<string, string> };
  assert.equal(manifest.peerDependencies?.["@repo/framework-generated"], "*");
  assert.equal(manifest.dependencies?.["@repo/framework-generated"], undefined);
});
