import { mkdir } from "node:fs/promises";
import path from "node:path";
import { test, expect, assertAccessible } from "./support/test";

for (const width of [1440, 390]) test(`GraphQL tabs browse source and prepare an explicit local query at ${width}px`, async ({ page, studio }, info) => {
  await page.setViewportSize({ width, height: 1000 });
  let runtime: "stopped" | "ready" = "stopped";
  studio.reply("GET", "/api/graphql/runtime", route => route.fulfill({ json: { status: runtime, endpoint: runtime === "ready" ? "http://127.0.0.1:3001/graphql" : null, message: runtime === "ready" ? "Local API is ready." : "Local API is stopped." } }));
  studio.reply("POST", "/api/graphql/execute", route => route.fulfill({ json: { status: 200, durationMs: 3, body: { data: { projects: [{ id: "fixture-project", name: "Fixture project" }] } } } }));
  await studio.goto("/graphql/schema");
  const tabs = page.getByRole("navigation", { name: "GraphQL sections", exact: true });
  await expect(tabs.getByRole("link", { name: "Schema", exact: true })).toHaveAttribute("aria-current", "page");
  await expect(page.locator('[data-chain-link="prisma-pothos"]')).toHaveAttribute("aria-current", "step");
  await page.getByRole("button", { name: "Project object", exact: true }).click();
  await expect(page.getByRole("region", { name: "Project fields", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "SDL", exact: true }).click();
  await expect(page.getByLabel("Project SDL", { exact: true })).toContainText("type Project");
  await tabs.getByRole("link", { name: "Client", exact: true }).focus(); await page.keyboard.press("Enter");
  await expect(page).toHaveURL(/\/graphql\/client$/);
  await expect(page.locator('[data-chain-link="generated-client"]')).toHaveAttribute("aria-current", "step");
  await expect(page.getByText("projects.id", { exact: true })).toBeVisible();
  await expect(page.getByLabel("projectKeys source", { exact: true })).toContainText('all: ["projects"]');
  await page.getByRole("button", { name: "Run in Explorer", exact: true }).click();
  await expect(page).toHaveURL(/\/graphql\/explorer\?document=projects$/);
  await expect(page.locator('[data-chain-link="pothos-generated"]')).toHaveAttribute("aria-current", "step");
  const operationEditor = page.getByRole("textbox", { name: "Operation document", exact: true });
  await expect(operationEditor).toHaveValue(/fragment ProjectSummary/);
  const run = page.getByRole("button", { name: "Run", exact: true });
  await expect(run).toBeDisabled();
  const token = page.getByLabel("Cognito ID token", { exact: true });
  await expect(token).toHaveAttribute("type", "password");
  await token.fill("fixture.synthetic.signature"); await expect(run).toBeDisabled();
  expect(studio.requests.filter(request => request.path === "/api/graphql/execute")).toHaveLength(0);
  runtime = "ready"; await page.getByRole("button", { name: "Check runtime", exact: true }).click();
  await expect(run).toBeEnabled();
  await run.focus(); await page.keyboard.press("Enter");
  await expect(page.getByLabel("GraphQL response", { exact: true })).toContainText("Fixture project");
  expect(studio.requests.filter(request => request.path === "/api/graphql/execute")).toHaveLength(1);
  expect(await page.evaluate(() => [...Object.values(localStorage), ...Object.values(sessionStorage)].some(value => String(value).includes("fixture.synthetic.signature")))).toBe(false);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  const evidence = path.resolve(__dirname, "../../../output/playwright/graphql-contract-chain/browser", info.project.name, `explorer-${width}.png`);
  await mkdir(path.dirname(evidence), { recursive: true }); await page.screenshot({ path: evidence });
  await assertAccessible(page);
  await page.reload(); await expect(page.getByLabel("Cognito ID token", { exact: true })).toHaveValue("");
  expect(studio.requests.filter(request => request.path === "/api/graphql/execute")).toHaveLength(1);
});

test("scratch mutations require an explicit fresh confirmation and failures stay visible", async ({ page, studio }) => {
  studio.reply("GET", "/api/graphql/runtime", route => route.fulfill({ json: { status: "ready", endpoint: "http://127.0.0.1:3001/graphql", message: "Local API is ready." } }));
  studio.reply("POST", "/api/graphql/execute", route => route.fulfill({ status: 401, json: { error: "The local API rejected the token." } }));
  await studio.goto("/graphql/explorer");
  await page.getByRole("textbox", { name: "Operation document", exact: true }).fill('mutation Scratch { archiveProject(id: "fixture") }');
  await page.getByLabel("Cognito ID token", { exact: true }).fill("fixture.synthetic.signature");
  const run = page.getByRole("button", { name: "Run", exact: true }); await expect(run).toBeDisabled();
  const confirm = page.getByRole("checkbox", { name: "Allow this run to change local data", exact: true });
  await confirm.check(); await expect(run).toBeEnabled();
  await run.click();
  await expect(page.getByRole("alert").filter({ hasText: "The local API rejected the token." })).toBeVisible();
  await expect(confirm).not.toBeChecked(); await expect(run).toBeDisabled();
  const requests = studio.requests.filter(request => request.path === "/api/graphql/execute");
  expect(requests).toHaveLength(1); expect(requests[0]?.body).toMatchObject({ confirmMutation: true, idToken: "fixture.synthetic.signature" });
  expect(studio.requests.filter(request => request.path.startsWith("/api/operations") && request.method === "POST")).toHaveLength(0);
});
