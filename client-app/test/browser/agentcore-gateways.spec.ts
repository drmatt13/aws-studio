import { test, expect, assertAccessible, type StudioFixture } from "./support/test";
import { location } from "./support/scenarios";
import { withConnectionAuthorizations } from "../../shared/permissions";

function gatewaysFixture(studio: StudioFixture) {
  for (const model of Object.values(studio.response.snapshot.models)) {
    const base = model.targets[0]!;
    const agent = { ...base, ref: "agent:gateway-agent", id: "gateway-agent", title: "Gateway agent", kind: "agent" as const, role: "agent" as const, auth: true,
      compute: { kind: "agent" as const, auth: true, gateways: ["arithmetic"] }, environment: [{ name: "FRAMEWORK_AGENTCORE_ADAPTER", via: "agentcore" as const, value: { kind: "literal" as const, value: "Generated gateway connections: arithmetic" } }], secrets: [], routes: [] };
    const tool = { ...base, ref: "lambda:arithmetic-tool", id: "arithmetic-tool", title: "Arithmetic tool", role: "tool" as const, auth: false, routes: [] };
    const gateway = { id: "gateway:agentcore:arithmetic" as const, key: "arithmetic", title: "Arithmetic gateway", protocol: "agentcore" as const, tools: [tool.id], consumers: [agent.ref], origin: 'gateways["arithmetic"]', constructId: "Arithmetic", constructIdPinned: false, lanes: base.lanes };
    const empty = { ...gateway, id: "gateway:agentcore:empty" as const, key: "empty", title: "Empty gateway", tools: [], consumers: [], origin: 'gateways["empty"]', constructId: "Empty" };
    Object.assign(model, { targets: [...model.targets, agent, tool], gateways: [...(model.gateways ?? []), gateway, empty], edges: [...model.edges,
      { id: "agent-gateway", from: agent.ref, to: gateway.id, relation: "usesGateway", label: gateway.key, provenance: "declared" },
      { id: "gateway-tool", from: gateway.id, to: tool.ref, relation: "usesTool", label: tool.id, provenance: "declared" }], fields: { ...model.fields, [agent.ref]: [] }, deployChoices: { ...model.deployChoices, agent: { both: {local:true,cloud:true,dev:false,prod:true}, "local-only": {local:true,cloud:false,dev:false,prod:false}, "cloud-only": {local:false,cloud:true,dev:false,prod:true}, none: {local:false,cloud:false,dev:false,prod:false} } } });
    Object.assign(model, withConnectionAuthorizations(model));
  }
  for (const [id, origin] of [["agent:gateway-agent", 'agents["gateway-agent"]'], ["gateway:agentcore:arithmetic", 'gateways["arithmetic"]'], ["gateway:agentcore:empty", 'gateways["empty"]']]) {
    Object.assign(studio.response.snapshot.source.entities, { [id]: { origin, key: location, value: location } });
    Object.assign(studio.response.snapshot.source.editability, { [id]: { tools: { kind: "literal", text: '[]' }, deploy: { kind: "literal", text: '"both"' }, gateways: { kind: "literal", text: '[]' } } });
  }
}

for (const width of [1440, 390]) test(`agents select and reorder gateways through reviewed drafts at ${width}px`, async ({ page, studio }) => {
  await page.setViewportSize({ width, height: 1000 });
  gatewaysFixture(studio);
  await studio.goto("/?select=agent%3Agateway-agent");
  const inspector = page.getByRole("complementary", { name: "Inspector", exact: true });
  await inspector.locator("[data-inspector-disclosure] > details > summary").filter({ hasText: /^Settings$/ }).click();
  const picker = inspector.getByRole("combobox", { name: "Add gateway", exact: true });
  await picker.selectOption("empty");
  const up = inspector.getByRole("button", { name: "Move Empty gateway up", exact: true });
  await up.focus(); await up.press("Enter");
  await expect(inspector.locator("[data-slot=agent-gateway-binding-name]")).toHaveText(["Empty gateway", "Arithmetic gateway"]);
  await page.getByRole("button", { name: "Review Changes", exact: true }).click();
  expect(JSON.stringify(studio.requests.find(request => request.path === "/api/edits/batch/plan")?.body)).toContain('"kind":"agentGateways","target":"agent:gateway-agent","gateways":["empty","arithmetic"]');
  await page.getByRole("button", { name: "Back to Editing", exact: true }).click();
  await expect(inspector.locator("[data-slot=agent-gateway-binding-name]")).toHaveText(["Empty gateway", "Arithmetic gateway"]);
  await page.getByRole("button", { name: "Discard", exact: true }).click();
  await expect(inspector.locator("[data-slot=agent-gateway-binding-name]")).toHaveText(["Arithmetic gateway"]);
  await inspector.locator("[data-inspector-disclosure] > details > summary").filter({ hasText: /^Configuration and inputs/ }).click();
  await expect(inspector).toContainText("FRAMEWORK_AGENTCORE_ADAPTER");
  await expect(inspector).toContainText("Generated by the framework from selected gateways.");
  await assertAccessible(page);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(studio.requests.filter(request => /apply$/.test(request.path))).toHaveLength(0);
});

test("AgentCore gateways expose tools and independent deployment with an empty state", async ({ page, studio }) => {
  gatewaysFixture(studio);
  await studio.goto("/?select=gateway%3Aagentcore%3Aempty");
  const inspector = page.getByRole("complementary", { name: "Inspector", exact: true });
  await expect(inspector.getByText("AgentCore Gateway", { exact: true })).toBeVisible();
  await inspector.locator("summary").filter({ hasText: /^Tools/ }).click();
  await expect(inspector).toContainText("No tools attached.");
  await inspector.getByRole("combobox", { name: "Add tool", exact: true }).selectOption("arithmetic-tool");
  await inspector.locator("summary").filter({ hasText: /^Settings/ }).click();
  await inspector.getByRole("combobox", { name: "Deploy", exact: true }).selectOption("none");
  await expect(inspector.locator("[data-slot=inspector-kind] [data-environment=prod]")).toHaveAttribute("data-enabled", "false");
  await page.getByRole("button", { name: "Review Changes", exact: true }).click();
  const body = JSON.stringify(studio.requests.find(request => request.path === "/api/edits/batch/plan")?.body);
  expect(body).toContain('"kind":"gatewayTools","gateway":"gateway:agentcore:empty","tools":["arithmetic-tool"]');
  expect(body).toContain('"kind":"gatewayDeploy","gateway":"gateway:agentcore:empty","value":"none"');
  await page.getByRole("button", { name: "Back to Editing", exact: true }).click();
  await page.getByRole("button", { name: "Discard", exact: true }).click();
  await assertAccessible(page);
});

for (const width of [1440, 390]) test(`API creator switches HTTP WebSocket and AgentCore while preserving identity at ${width}px`, async ({ page, studio }) => {
  await page.setViewportSize({ width, height: 1000 });
  await studio.goto();
  await page.getByRole("button", { name: "Add to application", exact: true }).click();
  await page.getByRole("dialog", { name: "Add to application", exact: true }).getByRole("button", { name: "API", exact: true }).click();
  const dialog = page.getByRole("dialog", { name: "Create API", exact: true });
  const type = dialog.getByRole("combobox", { name: "Type", exact: true });
  await expect(type).toHaveValue("http");
  await dialog.getByRole("textbox", { name: "Stable identifier", exact: true }).fill("new-gateway");
  await type.selectOption("webSocket");
  await expect(dialog.getByRole("textbox", { name: "Route path or WebSocket key", exact: true })).toHaveValue("new-gateway");
  await type.selectOption("agentcore");
  await expect(dialog.getByRole("textbox", { name: "Stable identifier", exact: true })).toHaveValue("new-gateway");
  await expect(dialog.getByRole("textbox", { name: "Implementation directory", exact: true })).toHaveCount(0);
  await expect(dialog.getByRole("textbox", { name: "Lambda tools", exact: true })).toBeVisible();
  await assertAccessible(page);
  await dialog.getByRole("button", { name: "Review generated changes", exact: true }).click();
  expect(JSON.stringify(studio.requests.find(request => request.path === "/api/edits/batch/plan")?.body)).toContain('"kind":"gateway"');
  await page.getByRole("button", { name: "Back to Editing", exact: true }).click();
  await dialog.getByRole("button", { name: "Cancel creation", exact: true }).click();
  expect(studio.requests.filter(request => /apply$/.test(request.path))).toHaveLength(0);
});
