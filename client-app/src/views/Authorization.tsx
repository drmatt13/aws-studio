import type { ReactNode } from "react";
import { buttonClasses } from "../ui/Button";
import { cx } from "../ui/classes";
import { authorizationLabel, type ConnectionAuthorization } from "../../shared/permissions";
import { useStudio } from "../studio";

/**
 * Labels only an exception. Permissions are IAM grants unless something says otherwise, so an IAM
 * badge on every row and heading was clutter; local connections, user tokens and source-only
 * evidence keep theirs because they change what the permission means.
 */
export function AuthorizationBadge({
  authorization,
  className,
}: {
  readonly authorization?: ConnectionAuthorization;
  readonly className?: string;
}) {
  return authorization && authorization.kind !== "iam" ? (
    <span
      className={cx(
        "inline-flex w-fit items-center rounded-sm border border-rule-strong px-1.5 py-0.5 font-sans text-[10px] font-semibold leading-[normal] tracking-[.035em] whitespace-nowrap",
        "text-graphite",
        className,
      )}
      data-slot="authorization-badge"
    >
      {authorizationLabel(authorization)}
    </span>
  ) : null;
}

/**
 * One block of declaration evidence: a principal's grant, or an explicit policy statement.
 * The caller places it, so `className` carries the block's margin.
 */
export function PermissionFacts({
  children,
  className,
  "data-slot": slot,
}: {
  readonly children: ReactNode;
  readonly className: string;
  readonly "data-slot"?: string;
}) {
  return (
    <dl
      className={cx("border-l-2 border-rule-strong bg-wash px-3 py-2.5 text-step-minus1", className)}
      data-slot={slot}
    >
      {children}
    </dl>
  );
}

/** A labelled value inside `PermissionFacts`; long identifiers wrap inside the block. */
export function PermissionFact({
  label,
  children,
}: {
  readonly label: string;
  readonly children: ReactNode;
}) {
  return (
    <div className="mb-2 last:mb-0">
      <dt className="text-meta text-ink">{label}</dt>
      <dd className="mx-0 mt-0.5 mb-0 wrap-anywhere">{children}</dd>
    </div>
  );
}

/** Declaration evidence, with the principal shown independently of the graph arrow. */
export function AuthorizationDetails({
  authorization,
}: {
  readonly authorization: ConnectionAuthorization;
}) {
  const { select } = useStudio();
  return (
    <div className="my-3.5" data-slot="authorization-details">
      <div className="flex flex-wrap items-center gap-2.5" data-slot="authorization-heading">
        <h3 className="m-0 text-label font-semibold text-balance">Authorization</h3>
        <AuthorizationBadge authorization={authorization} />
      </div>
      {authorization.kind === "iam" && authorization.state === "not-built" ? (
        <p
          className="mt-0 mb-2 border-l-2 border-local pl-2.5 text-step-minus1"
          data-slot="authorization-status"
        >
          Applies when this workload runs in AWS.
        </p>
      ) : null}
      {authorization.grants.map((grant, index) => (
        <PermissionFacts className="my-2.5" key={index} data-slot="authorization-grant">
          <PermissionFact label="Principal">
            {grant.principalEntity ? (
              <button
                className={buttonClasses({ variant: "link" })}
                onClick={() => select(grant.principalEntity!)}
              >
                {grant.principal}
              </button>
            ) : (
              grant.principal
            )}
          </PermissionFact>
          <PermissionFact label="Policy">{grant.policy}</PermissionFact>
          {grant.effect ? <PermissionFact label="Effect">{grant.effect}</PermissionFact> : null}
          {grant.actions ? (
            <PermissionFact label="Actions">
              <code>{grant.actions.join(", ")}</code>
            </PermissionFact>
          ) : null}
          {grant.via ? (
            <PermissionFact label="Generated by">
              <code>{grant.via}</code>
            </PermissionFact>
          ) : null}
          <PermissionFact label="Scope">{grant.scope}</PermissionFact>
          {grant.conditions?.length ? (
            <PermissionFact label="Conditions">{grant.conditions.join("; ")}</PermissionFact>
          ) : null}
        </PermissionFacts>
      ))}
      {authorization.notes.map((note) => (
        <p key={note} className="mt-0 mb-2 text-caption text-graphite">
          {note}
        </p>
      ))}
      {authorization.kind === "iam" ? (
        <p className="mt-0 mb-2 text-caption text-graphite">
          Derived from source declarations. Synthesis expands native grants; deployed policies and
          effective access are not verified here.
        </p>
      ) : null}
    </div>
  );
}
